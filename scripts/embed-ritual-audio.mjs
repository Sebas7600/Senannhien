import {mkdir,readFile,writeFile} from 'node:fs/promises';

// Bundle recordings as lazy JavaScript chunks instead of intercepted MP3/WAV requests.
const root=new URL('../',import.meta.url),out=new URL('src/generated/',root);
await mkdir(out,{recursive:true});
for(const [kind,file,mime] of [['bell','temple-bell-jnn.mp3','audio/mpeg'],['chant','truc-lam-pentatonic.wav','audio/wav']]){
  const bytes=await readFile(new URL(`public/audio/${file}`,root));
  const source=`// Generated by scripts/embed-ritual-audio.mjs; keep credits in public/audio/CREDITS.md.\nexport default ${JSON.stringify(`data:${mime};base64,${bytes.toString('base64')}`)};\n`;
  const target=new URL(`${kind}Audio.ts`,out);
  if(await readFile(target,'utf8').catch(()=>null)!==source)await writeFile(target,source);
}
